<?php

namespace App\Service\Carrier\MyDhl;

use Symfony\Component\Filesystem\Filesystem;

/**
 * Stores DHL shipment documents (label, commercial invoice) outside public/ —
 * they carry customer addresses, so they are only served through the
 * admin-only download controller, never by the web server directly.
 */
class DhlLabelStorage
{
    public function __construct(
        private readonly string $storageDirectory,
        private readonly Filesystem $filesystem = new Filesystem(),
    ) {
    }

    /**
     * @return string the stored file name (relative to the storage directory)
     */
    public function save(string $awb, string $type, string $pdfBytes): string
    {
        $fileName = sprintf('%s-%s.pdf', $this->sanitize($awb), $this->sanitize($type));
        $this->filesystem->dumpFile($this->storageDirectory . '/' . $fileName, $pdfBytes);

        return $fileName;
    }

    /**
     * Absolute path of a stored file, or null when it is missing.
     */
    public function getPath(string $fileName): ?string
    {
        // Stored names are generated by save(); reject anything that could escape the directory.
        if ($fileName !== basename($fileName) || !str_ends_with($fileName, '.pdf')) {
            return null;
        }

        $path = $this->storageDirectory . '/' . $fileName;

        return is_file($path) ? $path : null;
    }

    private function sanitize(string $value): string
    {
        return preg_replace('/[^A-Za-z0-9_-]/', '', $value) ?: 'unknown';
    }
}
